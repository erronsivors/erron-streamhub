export function hintText(id: string, mode: SetupMode | null): { title: string; body: string } | null {
  const h = HINTS[id]
  if (!h) return null
  const extra = mode === 'two' ? h.two : mode === 'one' ? h.one : undefined
  return { title: h.title, body: extra ? `${h.common}\n\n${extra}` : h.common }
}
